"""Bundle the project code + scene split into ONE script that runs as a Kaggle GPU job.

Kaggle scripts are a single file, so this pastes src/oiltank/{data,model,evaluate,train}.py
in order (dropping their package-internal imports), embeds data/splits.json, and adds a
main() that trains, picks the best epoch by val AP@0.5, and evaluates on the test scenes.

usage: python scripts/build_kaggle_job.py --user <kaggle-username>
       (or set KAGGLE_USERNAME) -> scratch/kaggle_train/{train_kaggle.py, kernel-metadata.json}
"""
import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "scratch/kaggle_train"
MODULES = ["data", "model", "evaluate", "train"]

MAIN = '''

# ---------------------------------------------------------------- Kaggle entry point
EPOCHS = 10
BATCH = 4
LR = 0.01


def find_dataset_root():
    """Kaggle mounts datasets under /kaggle/input; locate labels_coco.json there."""
    hits = sorted(Path("/kaggle/input").rglob("labels_coco.json"))
    print("labels_coco.json candidates:", [str(h) for h in hits])
    return hits[0].parent


def main():
    t_start = time.time()
    torch.manual_seed(0)
    random.seed(0)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    hardware = torch.cuda.get_device_name(0) if device == "cuda" else "cpu"
    print("device:", device, hardware)

    root = find_dataset_root()
    boxes = load_coco(root / "labels_coco.json")
    images = root / "image_patches"
    patches = SPLITS["patches"]
    for k in ("train", "val", "test"):
        print(f"{k}: {len(patches[k])} patches")

    def loader(split, train):
        ds = TankPatches(images, patches[split], boxes, train=train)
        return torch.utils.data.DataLoader(ds, batch_size=BATCH, shuffle=train,
                                           num_workers=2, collate_fn=collate)

    model = build_model().to(device)
    ckpt = Path("/kaggle/working/best.pth")
    t0 = time.time()
    history = fit(model, loader("train", True), loader("val", False), EPOCHS, device, ckpt, lr=LR)
    train_seconds = time.time() - t0

    best = build_model(pretrained=False)
    best.load_state_dict(torch.load(ckpt, map_location=device))
    best.to(device).eval()
    preds, gts = predict(best, loader("test", False), device)
    results = {
        "hardware": hardware,
        "epochs": EPOCHS, "batch": BATCH, "lr": LR,
        "train_seconds": train_seconds,
        "total_seconds": time.time() - t_start,
        "best_epoch": max(history, key=lambda h: h["val_ap50"])["epoch"],
        "history": history,
        "test_scenes": SPLITS["scenes"]["test"],
        "patches_per_split": {k: {"total": len(patches[k]),
                                  "with_tanks": sum(len(boxes[n]) > 0 for n in patches[k]),
                                  "without_tanks": sum(len(boxes[n]) == 0 for n in patches[k])}
                              for k in ("train", "val", "test")},
        "test_ap50": average_precision(preds, gts),
        "test_at_conf_0.5": precision_recall_at(preds, gts, conf=0.5),
    }
    json.dump(results, open("/kaggle/working/results.json", "w"), indent=1)
    print(json.dumps({k: v for k, v in results.items() if k != "history"}, indent=1))


if __name__ == "__main__":
    main()
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", default=os.environ.get("KAGGLE_USERNAME"))
    user = ap.parse_args().user
    if not user:
        raise SystemExit("pass --user or set KAGGLE_USERNAME")
    OUT.mkdir(parents=True, exist_ok=True)
    parts = ['"""Auto-generated by scripts/build_kaggle_job.py -- do not edit by hand.\n\n'
             'Trains the oil-tank detector on a Kaggle GPU with the scene-level split from\n'
             'data/splits.json (embedded below)."""\n'
             "import json\nimport random\nimport time\nfrom pathlib import Path\n"]
    for m in MODULES:
        src = (ROOT / "src/oiltank" / f"{m}.py").read_text()
        src = "\n".join(l for l in src.splitlines() if not l.startswith("from oiltank."))
        parts.append(f"\n# ---------------------------------------------------------------- {m}.py\n{src}\n")
    splits = json.load(open(ROOT / "data/splits.json"))
    keep = {"seed": splits["seed"], "scenes": splits["scenes"], "patches": splits["patches"]}
    # the split only holds numbers, strings and lists, so its JSON text is valid Python
    parts.append(f"\nSPLITS = {json.dumps(keep)}\n")
    parts.append(MAIN)
    (OUT / "train_kaggle.py").write_text("".join(parts))

    meta = {
        "id": f"{user}/oil-tank-detector-train",
        "title": "oil-tank-detector-train",
        "code_file": "train_kaggle.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,          # needed once to fetch COCO-pretrained weights (74 MB)
        "dataset_sources": ["towardsentropy/oil-storage-tanks"],
        "competition_sources": [],
        "kernel_sources": [],
    }
    json.dump(meta, open(OUT / "kernel-metadata.json", "w"), indent=2)
    print("wrote", OUT / "train_kaggle.py", "and", OUT / "kernel-metadata.json")


if __name__ == "__main__":
    main()
